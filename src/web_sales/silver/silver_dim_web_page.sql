-- Silver: cleansed web-page dimension with business column names.
-- A web page is the site page a web-sales line was ordered from.
-- Business key: web_page_key. TPC-DS web_page carries slowly-changing history; keep only
-- the current record.
CREATE OR REFRESH MATERIALIZED VIEW silver.dim_web_page (
  CONSTRAINT valid_web_page_key EXPECT (web_page_key IS NOT NULL) ON VIOLATION DROP ROW
)
  COMMENT 'Cleansed web pages, current records only. Source: bronze.web_page.'
AS
SELECT
  wp_web_page_sk                      AS web_page_key,
  wp_web_page_id                      AS web_page_id,
  wp_type                             AS page_type,
  wp_char_count                       AS char_count,
  wp_link_count                       AS link_count,
  wp_image_count                      AS image_count,
  CAST(wp_autogen_flag = 'Y' AS BOOLEAN) AS is_autogenerated
FROM bronze.web_page
WHERE wp_rec_end_date IS NULL;
