-- Gold presentation table: the web-sales fact widened with the descriptive dimension
-- columns the semantic layer needs. The Metric View and Genie read this one table, so they
-- need no joins. It reads the conformed core dims (item, customer, date, promotion) owned
-- by the core pipeline and the web-only dims (web site, web page).
-- Grain: one web-sales order line (order_number x item_key).
CREATE OR REFRESH MATERIALIZED VIEW gold.web_sales_enriched
  COMMENT 'Wide web-sales table for the Metric View and Genie. Source: gold.fct_web_sales + dims. domain=Web Sales'
AS
SELECT
  f.order_number,
  f.date_key,
  f.sold_date,
  d.calendar_year,
  d.month_name,
  d.quarter_of_year,
  f.item_key,
  i.item_name,
  i.brand,
  i.class,
  i.category,
  i.manufacturer,
  f.customer_key,
  c.customer_state,
  c.customer_country,
  f.web_site_key,
  ws.web_site_name,
  ws.web_site_class,
  ws.web_site_state,
  ws.web_site_country,
  f.web_page_key,
  wp.page_type,
  wp.is_autogenerated,
  f.promo_key,
  p.promo_name,
  p.promo_purpose,
  f.quantity,
  f.list_price,
  f.sales_price,
  f.wholesale_cost,
  f.sales_amount,
  f.discount_amount,
  f.net_paid,
  f.net_profit
FROM gold.fct_web_sales AS f
JOIN gold.dim_item       AS i  ON f.item_key     = i.item_key
JOIN gold.dim_customer   AS c  ON f.customer_key = c.customer_key
JOIN gold.dim_date       AS d  ON f.date_key     = d.date_key
LEFT JOIN gold.dim_web_site   AS ws ON f.web_site_key = ws.web_site_key
LEFT JOIN gold.dim_web_page   AS wp ON f.web_page_key = wp.web_page_key
LEFT JOIN gold.dim_promotion  AS p  ON f.promo_key    = p.promo_key;
